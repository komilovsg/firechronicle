interface Env {
  KV: KVNamespace;
  GEMINI_API_KEY: string;
  DEBUG_TOKEN: string;
  RETRIEVAL_MODE?: string;
  THRESHOLD?: string;
  RATE_SALT?: string;
}

const DISCLOSURE = "Answers are generated by an SI model from the FireChronicle knowledge base and checked for unsupported numbers.";
const INDEX = indexData as unknown as { version: string; facts_generated_at?: string; facts_data_through?: string; chunks: Chunk[] };

let appliedMemo: { key: string; chunks: Chunk[] } | null = null;
/** Chunks with live data-derived text (or the baked text when live data is unavailable). */
async function currentChunks(env: Env): Promise<{ chunks: Chunk[]; status: FactsStatus; version: string }> {
  const live = await getLiveFacts(env.KV);
  if (live.stale) log({ event: "facts_stale" });
  if (!live.data) {
    return { chunks: INDEX.chunks, status: { ...live.status, generated_at: INDEX.facts_generated_at ?? null, data_through: INDEX.facts_data_through ?? null }, version: `b${INDEX.version}` };
  }
  const key = `${live.status.generated_at}|${live.data.partial?.days ?? ""}|${live.data.partial?.t_month ?? ""}`;
  if (!appliedMemo || appliedMemo.key !== key) appliedMemo = { key, chunks: applyFacts(INDEX.chunks, live.data) };
  return { chunks: appliedMemo.chunks, status: live.status, version: `l${INDEX.version}${key}` };
}
const CACHE_TTL = 7 * 86400;
const EMBED_TTL = 30 * 86400;

const json = (body: unknown, status: number, extra: Record<string, string> = {}) =>
  new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json; charset=utf-8", ...extra } });

function log(o: Record<string, unknown>) { console.log(JSON.stringify(o)); }

async function readBody(req: Request): Promise<{ ok: true; data: Record<string, unknown> } | { ok: false; status: number; error: string }> {
  const buf = await req.arrayBuffer();
  if (buf.byteLength > MAX_BODY_BYTES) return { ok: false, status: 413, error: "Request body is too large (max 4 KB)." };
  try {
    const data = JSON.parse(new TextDecoder().decode(buf));
    if (typeof data !== "object" || data === null || Array.isArray(data)) throw new Error();
    return { ok: true, data };
  } catch { return { ok: false, status: 400, error: "Body must be a JSON object." }; }
}

async function embedCached(env: Env, q: string): Promise<number[] | null> {
  const key = `emb:${await sha256Hex(q.toLowerCase())}`;
  const hit = await env.KV.get(key, "json");
  if (hit) return hit as number[];
  const v = await embedQuery(env, q);
  if (v) await env.KV.put(key, JSON.stringify(v.map((x) => Math.round(x * 1e5) / 1e5)), { expirationTtl: EMBED_TTL });
  return v;
}

function renderSources(final: Final, ctx: CtxChunk[]) {
  const seen = new Set<string>();
  const out: { title: string; section: string; url: string }[] = [];
  for (const id of final.sourceIds) {
    const c = ctx[id - 1];
    if (!c) continue;
    const s = c.title ? { title: c.title, section: c.section ?? "", url: c.url ?? "" } : { title: c.source, section: "", url: "" };
    const k = `${s.title}|${s.section}`;
    if (!seen.has(k)) { seen.add(k); out.push(s); }
  }
  return out;
}

async function handleAsk(req: Request, env: Env, cors: Record<string, string>, debugOk: boolean): Promise<Response> {
  const t0 = Date.now();
  const body = await readBody(req);
  if (!body.ok) return json({ error: body.error }, body.status, cors);
  const q = cleanQuestion(body.data.q);
  if (!q) return json({ error: "Question must be 3-500 characters." }, 400, cors);
  const lang: Lang = body.data.lang === "ru" || body.data.lang === "tg" ? body.data.lang : "en";
  if (body.data.lang !== undefined && !["en", "ru", "tg"].includes(body.data.lang as string)) return json({ error: "lang must be en, ru or tg." }, 400, cors);
  const av = validateArea(body.data.area);
  if (!av.ok) return json({ error: av.error }, 400, cors);
  const area: Area | null = av.area;

  if (!debugOk) {
    const ip = req.headers.get("cf-connecting-ip") ?? "unknown";
    const rate = await checkRate(env.KV, ip, env.RATE_SALT ?? "salt");
    if (rate !== "ok") {
      return json({
        error: rate === "minute" ? "Too many questions. Please wait a minute and try again." : "Daily question limit reached. Please try again tomorrow.",
        refused: true, reason: "rate_limit",
      }, 429, { ...cors, "retry-after": rate === "minute" ? "60" : "3600" });
    }
  }

  const qh = (await sha256Hex(q.toLowerCase())).slice(0, 12);
  const cur = await currentChunks(env);
  const cacheKey = `ans:${await sha256Hex(cur.version)}:${await sha256Hex(`${q.toLowerCase()}|${lang}|${JSON.stringify(area?.facts ?? null)}|${area?.name ?? ""}`)}`;
  if (!debugOk) {
    const hit = await env.KV.get(cacheKey, "json");
    if (hit) { log({ qh, cached: true, ms: Date.now() - t0 }); return json({ ...(hit as object), disclosure: DISCLOSURE, cached: true }, 200, cors); }
  }

  const dbg: Record<string, unknown> = {};
  const finish = async (res: Record<string, unknown>, cache: boolean, reason?: string, model?: string) => {
    if (cache) await env.KV.put(cacheKey, JSON.stringify(res), { expirationTtl: CACHE_TTL });
    log({ qh, reason: reason ?? "ok", model: model ?? null, ms: Date.now() - t0 });
    if (debugOk) { dbg.ms_total = Date.now() - t0; res = { ...res, debug: dbg }; }
    return json({ ...res, disclosure: DISCLOSURE, cached: false }, 200, cors);
  };

  const t1 = Date.now();
  const qv = await embedCached(env, q);
  if (!qv) { log({ qh, reason: "embed_failed", ms: Date.now() - t0 }); return json({ error: "The assistant is temporarily unavailable. Please try again." }, 503, cors); }
  dbg.ms_embed = Date.now() - t1;

  const mode: Mode = env.RETRIEVAL_MODE === "vector" ? "vector" : "hybrid";
  const modeOverride = debugOk ? req.headers.get("x-retrieval-mode") : null;
  const threshold = Number(env.THRESHOLD ?? "0.5");
  const rr = retrieve(q, qv, cur.chunks, { mode: modeOverride === "vector" || modeOverride === "hybrid" ? modeOverride : mode, topK: 4 });
  dbg.retrieved = rr.hits.map((h) => ({
    id: h.chunk.id, title: h.chunk.title, section: h.chunk.section, sim: +h.sim.toFixed(4),
    vecRank: h.vecRank, bm25Rank: h.bm25Rank, rrf: +h.rrf.toFixed(5), pinned: h.pinned, text: h.chunk.text,
  }));
  dbg.facts = cur.status; dbg.maxSim = +rr.maxSim.toFixed(4); dbg.threshold = threshold; dbg.identifiers = rr.identifiers; dbg.mode = modeOverride ?? mode;

  if (rr.maxSim < threshold && rr.pinnedCount === 0) {
    dbg.chat_calls = 0;
    return finish({ answer: REFUSAL[lang], refused: true, reason: "out_of_scope", sources: [] }, true, "out_of_scope");
  }

  const ctx = toCtx(rr.hits.map((h) => h.chunk), area);
  const system = systemPrompt(lang);
  const user = buildUserMessage(ctx, q);
  dbg.prompt = { system, user };
  const ctxText = ctx.map((c) => c.text).join("\n");
  const overlapPick = (text: string) => {
    const words = new Set(text.toLowerCase().match(/[a-z0-9]{4,}/g) ?? []);
    let best: number | null = null, bs = 0;
    for (const c of ctx) {
      const s = (c.text.toLowerCase().match(/[a-z0-9]{4,}/g) ?? []).filter((w) => words.has(w)).length;
      if (s > bs) { bs = s; best = c.n; }
    }
    return best;
  };

  const raws: string[] = [];
  let exclude: string[] = [];
  let models = CHAT_MODELS;
  let final: Final | null = null;
  let usedModel: string | undefined;
  dbg.attempts = [];
  for (let pass = 0; pass < 2; pass++) {
    if (!(await bumpGlobal(env.KV))) {
      return finish({ answer: "The assistant has reached today's free limit. It resets at 00:00 UTC.", refused: true, reason: "limit", sources: [] }, false, "global_cap");
    }
    const t2 = Date.now();
    const r = await chat(env, { system, user, models }, exclude);
    (dbg.attempts as unknown[]).push(...r.attempts);
    dbg.ms_chat = ((dbg.ms_chat as number) ?? 0) + (Date.now() - t2);
    if (!r.ok) {
      if (pass === 1) break; // keep the first (unverified) outcome => refuse below
      if (r.reason === "limit") {
        return finish({ answer: `The assistant has reached today's free limit. It resets at ${fmtUtc(r.resetAt)}.`, refused: true, reason: "limit", sources: [] }, false, "limit");
      }
      log({ qh, reason: "chat_unavailable" });
      return json({ error: "The assistant is temporarily unavailable. Please try again." }, 503, cors);
    }
    raws.push(r.text);
    usedModel = r.model;
    const f = postProcess(r.text, ctx, lang, overlapPick);
    if (f.citationMissing) log({ qh, event: "citation_missing", model: r.model });
    if (f.refused) { final = f; break; }
    const bad = findUnverifiedNumbers(f.answer, ctxText);
    if (bad.length === 0) { final = f; break; }
    dbg.unverified = bad;
    exclude = [r.model];
    models = CHAT_MODELS.slice(CHAT_MODELS.indexOf(r.model) + 1);
    if (!models.length) break;
  }
  dbg.raw_outputs = raws; dbg.chat_calls = raws.length;
  if (!final) {
    final = { answer: REFUSAL[lang], refused: true, reason: "unverified_number", sourceIds: [], citationMissing: false };
  }
  const res: Record<string, unknown> = {
    answer: final.answer, refused: final.refused, ...(final.reason ? { reason: final.reason } : {}),
    sources: final.refused ? [] : renderSources(final, ctx), model: usedModel,
  };
  void AREA_SOURCE;
  return finish(res, true, final.reason, usedModel);
}

async function handleNav(req: Request, env: Env, cors: Record<string, string>, debugOk: boolean): Promise<Response> {
  const t0 = Date.now();
  const body = await readBody(req);
  if (!body.ok) return json({ error: body.error }, body.status, cors);
  const q = cleanQuestion(body.data.q);
  if (!q) return json({ error: "Request must be 3-500 characters." }, 400, cors);
  if (!debugOk) {
    const rate = await checkRate(env.KV, req.headers.get("cf-connecting-ip") ?? "unknown", env.RATE_SALT ?? "salt");
    if (rate !== "ok") return json({ error: "Too many requests. Please wait and try again.", refused: true, reason: "rate_limit" }, 429, { ...cors, "retry-after": "60" });
  }
  const key = `nav:v2:${await sha256Hex(q.toLowerCase())}`;
  const hit = await env.KV.get(key, "json");
  if (hit) return json({ ...(hit as object), cached: true }, 200, cors);
  if (!(await bumpGlobal(env.KV))) return json({ refused: true, reason: "limit" }, 200, cors);
  const user = `<request>${q.replace(/</g, "‹").replace(/>/g, "›")}</request>`;
  const r = await chat(env, { system: NAV_SYSTEM, user, schema: NAV_SCHEMA });
  if (!r.ok) {
    if (r.reason === "limit") return json({ refused: true, reason: "limit" }, 200, cors);
    return json({ error: "The assistant is temporarily unavailable. Please try again." }, 503, cors);
  }
  let state = null;
  try { state = validateNav(JSON.parse(r.text)); } catch { state = null; }
  state = applyNavKeywords(q, state);
  const res = state ? { refused: false, state, action: state, model: r.model } : { refused: true, reason: "no_state", model: r.model };
  await env.KV.put(key, JSON.stringify(res), { expirationTtl: CACHE_TTL });
  log({ qh: (await sha256Hex(q.toLowerCase())).slice(0, 12), route: "nav", reason: state ? "ok" : "no_state", model: r.model, ms: Date.now() - t0 });
  return json({ ...res, cached: false }, 200, cors);
}

export default {
  async fetch(req: Request, env: Env): Promise<Response> {
    const url = new URL(req.url);
    const cd = corsDecision(req.headers.get("origin"));
    if (!cd.allowed) return json({ error: "Origin not allowed." }, 403);
    if (req.method === "OPTIONS") return new Response(null, { status: 204, headers: cd.headers });
    const debugTok = req.headers.get("x-debug-token");
    const debugOk = !!debugTok && !!env.DEBUG_TOKEN && (await sha256Hex(debugTok)) === (await sha256Hex(env.DEBUG_TOKEN));

    if (url.pathname === "/health" && req.method === "GET") {
      const cur = await currentChunks(env);
      return json({ ok: true, facts: cur.status, models: await healthModels(env.KV) }, 200, cd.headers);
    }
    if (req.method === "POST" && (url.pathname === "/ask" || url.pathname === "/nav")) {
      try {
        return url.pathname === "/ask" ? await handleAsk(req, env, cd.headers, debugOk) : await handleNav(req, env, cd.headers, debugOk);
      } catch (e) {
        log({ reason: "exception", err: String((e as Error)?.message ?? e).slice(0, 120) });
        return json({ error: "Internal error." }, 500, cd.headers);
      }
    }
    return json({ error: "Not found." }, 404, cd.headers);
  },
};
