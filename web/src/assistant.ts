import { ask, buildAskBody, nav, LANGS, type Answer, type Lang, type NavAction, type NavLimits } from './lib/assistant';
import { openInfoSheet } from './ui/sheet';

/** API base of the SI assistant worker. Empty until the URL is known; when set, add its origin to the CSP connect-src. */
export const ASSISTANT_URL = '';
const CHIPS: Record<Lang, string[]> = {
  en: ['What is a hotspot?', 'Why do MODIS and VIIRS differ?', 'Is this month normal here?', 'What does harmonized mean?', 'When is the fire season in this area?', 'How accurate is this data?'],
  ru: ['Когда сезон пожаров здесь?', 'Этот месяц выше нормы?', 'Почему нельзя просто склеить MODIS и VIIRS?', 'Что такое hotspot?'],
  tg: ['Мавсими сӯхтор кай аст?', 'Ин моҳ аз меъёр баланд аст?', 'Чаро MODIS ва VIIRS-ро якҷоя кардан мумкин нест?', 'Hotspot чист?'],
};
const DISCLOSURE_DEFAULT = 'Answers are generated by an SI assistant from the project’s knowledge base. Check important facts in the Methodology section.';

export interface AssistantHost { areaName(): string; facts(): Record<string, unknown>; limits(): NavLimits; apply(a: NavAction): string }
type Msg = { role: 'user' | 'bot' | 'notice' | 'loading'; text: string; answer?: Answer };

const el = <K extends keyof HTMLElementTagNameMap>(tag: K, cls?: string, text?: string): HTMLElementTagNameMap[K] => { const e = document.createElement(tag); if (cls) e.className = cls; if (text !== undefined) e.textContent = text; return e; };
const state = { lang: 'en' as Lang, mode: 'ask' as 'ask' | 'go', msgs: [] as Msg[], busy: false, draft: '' };
let langRefresh: () => void = () => {};
let host: AssistantHost, drawer: HTMLElement | null = null, closeSheet: (() => void) | null = null, active: { log: HTMLElement; input: HTMLInputElement; chips: HTMLElement; send: HTMLButtonElement; explain: HTMLButtonElement; notice: HTMLElement } | null = null, opener: HTMLElement | null = null;

function renderLog(): void {
  if (!active) return;
  const { log, chips } = active; log.textContent = '';
  chips.hidden = state.msgs.length > 0;
  for (const m of state.msgs) {
    const b = el('div', `am ${m.role}`);
    if (m.role === 'loading') { b.textContent = 'Thinking…'; b.setAttribute('aria-busy', 'true'); }
    else if (m.role === 'bot' && m.answer) {
      const a = m.answer;
      if (a.refused) { b.classList.add('refused'); b.append(el('p', 'rf', a.reason || 'Not in the knowledge base.')); if (a.answer) b.append(el('p', undefined, a.answer)); }
      else b.append(el('p', undefined, a.answer));
      if (a.sources.length) {
        const ul = el('ul', 'srcs'); ul.setAttribute('aria-label', 'Sources');
        for (const s of a.sources) {
          const li = el('li'); const label = s.section ? `${s.title} – ${s.section}` : s.title;
          if (s.url) { const link = el('a', undefined, label) as HTMLAnchorElement; link.href = s.url; link.target = '_blank'; link.rel = 'noopener noreferrer'; li.append(link); } else li.textContent = label;
          ul.append(li);
        }
        b.append(ul);
      }
      const meta = [a.cached ? 'cached' : '', a.model ?? ''].filter(Boolean).join(' · ');
      if (meta) b.append(el('p', 'meta', meta));
      b.append(el('p', 'disc', a.disclosure || DISCLOSURE_DEFAULT));
    } else b.textContent = m.text;
    log.append(b);
  }
  log.scrollTop = log.scrollHeight;
}
function setBusy(v: boolean): void { state.busy = v; if (active) { active.send.disabled = v || !ASSISTANT_URL; active.explain.disabled = v || !ASSISTANT_URL; } }
function errText(kind: string, retry: number | null): string {
  if (kind === 'rate') return `Too many questions right now. Please try again ${retry ? `in ${retry} seconds` : 'in a minute'}.`;
  if (kind === 'network') return 'Could not reach the SI assistant. Check your connection and try again.';
  if (kind === 'unconfigured') return 'The SI assistant is not connected yet.';
  return 'The SI assistant returned an unexpected answer. Please try again.';
}
const fetchImpl = (u: string, i: { method: string; headers: Record<string, string>; body: string }) => fetch(u, i);

async function send(q: string, withArea = false): Promise<void> {
  q = q.trim(); if (!q || state.busy) return;
  state.msgs.push({ role: 'user', text: q }, { role: 'loading', text: '' }); state.draft = ''; if (active) active.input.value = '';
  setBusy(true); renderLog();
  const done = (m: Msg): void => { state.msgs = state.msgs.filter((x) => x.role !== 'loading'); state.msgs.push(m); setBusy(false); renderLog(); };
  if (state.mode === 'go' && !withArea) {
    const r = await nav(fetchImpl, ASSISTANT_URL, q, host.limits());
    if (!r.ok) return done({ role: 'notice', text: errText(r.error.kind, r.error.kind === 'rate' ? r.error.retryAfter : null) });
    if (r.value.refused || !r.value.action) return done({ role: 'notice', text: 'I could not turn that into a view. Try naming an area, years or a calendar mode.' });
    return done({ role: 'notice', text: host.apply(r.value.action) });
  }
  const body = buildAskBody(q, state.lang, withArea ? { name: host.areaName(), facts: host.facts() } : undefined);
  const r = await ask(fetchImpl, ASSISTANT_URL, body);
  if (!r.ok) return done({ role: 'notice', text: errText(r.error.kind, r.error.kind === 'rate' ? r.error.retryAfter : null) });
  done({ role: 'bot', text: r.value.answer, answer: r.value });
}

function build(): HTMLElement {
  const root = el('div', 'assist');
  const head = el('div', 'a-head'); head.append(el('h2', undefined, 'Ask FireChronicle'));
  const lang = el('div', 'seg'); lang.setAttribute('role', 'group'); lang.setAttribute('aria-label', 'Answer language');
  LANGS.forEach((l) => { const b = el('button', undefined, l.label); b.type = 'button'; b.setAttribute('aria-pressed', String(state.lang === l.id)); b.addEventListener('click', () => { state.lang = l.id; [...lang.children].forEach((c, i) => c.setAttribute('aria-pressed', String(LANGS[i].id === l.id))); langRefresh(); }); lang.append(b); });
  head.append(lang);
  const notice = el('p', 'a-note'); notice.hidden = !!ASSISTANT_URL; notice.textContent = 'The SI assistant is not connected yet. This preview shows the interface only.';
  const mode = el('div', 'seg'); mode.setAttribute('role', 'group'); mode.setAttribute('aria-label', 'Mode');
  for (const [id, label] of [['ask', 'Ask'], ['go', 'Go to a view']] as const) { const b = el('button', undefined, label); b.type = 'button'; b.setAttribute('aria-pressed', String(state.mode === id)); b.addEventListener('click', () => { state.mode = id; [...mode.children].forEach((c, i) => c.setAttribute('aria-pressed', String(i === (id === 'ask' ? 0 : 1)))); input.placeholder = id === 'ask' ? 'Ask about fire, sensors or this page' : 'e.g. Show Tajikistan, 2015 to 2025, naive splice'; }); mode.append(b); }
  const log = el('div', 'a-log'); log.setAttribute('role', 'log'); log.setAttribute('aria-live', 'polite'); log.setAttribute('aria-label', 'Conversation');
  const chips = el('div', 'a-chips');
  const fillChips = (): void => { chips.textContent = ''; CHIPS[state.lang].forEach((c) => { const b = el('button', 'a-chip', c); b.type = 'button'; b.addEventListener('click', () => { state.mode = 'ask'; mode.children[0].dispatchEvent(new Event('click')); void send(c); }); chips.append(b); }); };
  fillChips(); langRefresh = fillChips;
  const explain = el('button', 'btn', 'Explain this area'); explain.type = 'button'; explain.addEventListener('click', () => { state.mode = 'ask'; void send('Explain this area for a non-expert.', true); });
  const form = el('form', 'a-form'); const input = el('input'); input.type = 'text'; input.maxLength = 500; input.placeholder = 'Ask about fire, sensors or this page'; input.setAttribute('aria-label', 'Your question'); input.autocomplete = 'off'; input.value = state.draft;
  input.addEventListener('input', () => { state.draft = input.value; });
  const sendB = el('button', 'btn primary', 'Send'); sendB.type = 'submit';
  form.append(input, sendB); form.addEventListener('submit', (e) => { e.preventDefault(); void send(input.value); });
  const foot = el('p', 'a-foot', DISCLOSURE_DEFAULT);
  root.append(head, notice, mode, log, chips, explain, form, foot);
  active = { log, input, chips, send: sendB, explain, notice };
  setBusy(state.busy); renderLog();
  return root;
}
export function isAssistantOpen(): boolean { return !!drawer || !!closeSheet; }
export function closeAssistant(): void {
  if (drawer) { drawer.remove(); drawer = null; active = null; opener?.focus(); }
  if (closeSheet) { closeSheet(); closeSheet = null; active = null; }
}
export function toggleAssistant(from?: HTMLElement | null): void {
  if (isAssistantOpen()) { closeAssistant(); return; }
  opener = from ?? (document.activeElement as HTMLElement | null);
  const root = build();
  if (matchMedia('(max-width: 640px)').matches) { closeSheet = openInfoSheet('Ask FireChronicle', root, opener, { tall: true }); }
  else {
    drawer = el('aside', 'assist-drawer'); drawer.setAttribute('role', 'dialog'); drawer.setAttribute('aria-label', 'Ask FireChronicle');
    const x = el('button', 'a-x', '×'); x.type = 'button'; x.setAttribute('aria-label', 'Close assistant'); x.addEventListener('click', closeAssistant);
    drawer.append(x, root); document.body.append(drawer);
    drawer.addEventListener('keydown', (e) => { if (e.key === 'Escape') { e.preventDefault(); e.stopPropagation(); closeAssistant(); } });
  }
  active?.input.focus({ preventScroll: true });
}
export function initAssistant(h: AssistantHost): void {
  host = h;
  document.getElementById('ask-btn')?.addEventListener('click', (e) => toggleAssistant(e.currentTarget as HTMLElement));
  window.addEventListener('keydown', (e) => {
    if (e.ctrlKey || e.metaKey || e.altKey || (e.key !== 'a' && e.key !== 'A')) return;
    const t = e.target as HTMLElement | null, tag = t?.tagName ?? '';
    if (tag === 'INPUT' || tag === 'SELECT' || tag === 'TEXTAREA' || t?.isContentEditable || document.querySelector('.tour, .fs-overlay:not([hidden])')) return;
    e.preventDefault(); toggleAssistant(null);
  });
}
